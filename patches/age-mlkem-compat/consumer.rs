// Exercise the same passphrase API used by codex-secrets/src/local.rs.
pub fn encrypt(plaintext: &[u8], passphrase: &age::secrecy::SecretString) -> Vec<u8> {
    let recipient = age::scrypt::Recipient::new(passphrase.clone());
    age::encrypt(&recipient, plaintext).expect("encrypt")
}

pub fn decrypt(ciphertext: &[u8], passphrase: &age::secrecy::SecretString) -> Vec<u8> {
    let identity = age::scrypt::Identity::new(passphrase.clone());
    age::decrypt(&identity, ciphertext).expect("decrypt")
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn codex_secrets_scrypt_roundtrip_and_tamper_rejection() {
        let passphrase = age::secrecy::SecretString::from("compatibility test only".to_owned());
        let plaintext = b"bounded compatibility probe, no real credentials";
        let mut ciphertext = encrypt(plaintext, &passphrase);
        assert_eq!(decrypt(&ciphertext, &passphrase), plaintext);
        let last = ciphertext.len() - 1;
        ciphertext[last] ^= 1;
        let identity = age::scrypt::Identity::new(passphrase);
        assert!(age::decrypt(&identity, &ciphertext).is_err());
    }

    #[test]
    fn upstream_post_quantum_recipient_still_encrypts() {
        let recipient: age::tagpq::Recipient = include_str!("tagpq-recipient.txt").parse().unwrap();
        let ciphertext = age::encrypt(&recipient, b"public post-quantum compatibility probe").unwrap();
        assert!(ciphertext.windows(b"mlkem768p256tag".len()).any(|w| w == b"mlkem768p256tag"));
    }

    #[test]
    #[ignore = "requires fixtures generated by repro.py interop"]
    fn released_ciphertext_is_readable_and_write_current_fixture() {
        let path = std::env::var("AGE_COMPAT_FIXTURES").expect("repro.py interop supplies fixtures");
        let dir = std::path::Path::new(&path);
        let passphrase = age::secrecy::SecretString::from("compatibility test only".to_owned());
        let plaintext = b"bounded compatibility probe, no real credentials";
        assert_eq!(decrypt(&std::fs::read(dir.join("released.age")).unwrap(), &passphrase), plaintext);
        std::fs::write(dir.join("upstream.age"), encrypt(plaintext, &passphrase)).unwrap();
    }
}
